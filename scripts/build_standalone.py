"""Build single-file, paste-into-Windmill versions of the two runnables.

A Windmill Python script is one file with a `def main(...)`; it cannot import
this repo's `core/` package. This inlines the needed core modules into one
self-contained file per runnable (pure stdlib, no `from core` import), so the
script pastes straight into a Windmill workspace and runs. Rebuilt from the real
sources, so the standalone files never drift from the tested core.

    python scripts/build_standalone.py

Writes windmill/standalone/{delta_reliability,judge_calibration}_standalone.py.
"""

from __future__ import annotations

import os
import re

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))

# Which core modules each runnable needs, in dependency order.
TARGETS = {
    "delta_reliability": {
        "core": ["core/wilson.py", "core/resampling.py", "core/reliability.py"],
        "entry": "windmill/delta_reliability.py",
        "demo": (
            'if __name__ == "__main__":\n'
            "    a = {\"c1\": [True, True, False], \"c2\": [False, False, True]}\n"
            "    b = {\"c1\": [True, True, True], \"c2\": [True, False, True]}\n"
            "    print(_render(main(a, b, \"v1\", \"v2\")))\n"
        ),
    },
    "judge_calibration": {
        "core": ["core/calibration.py"],
        "entry": "windmill/judge_calibration.py",
        "demo": (
            'if __name__ == "__main__":\n'
            "    gold = {f\"c{i}\": (i % 3 != 0) for i in range(12)}\n"
            "    scores = {f\"c{i}\": (0.8 if i % 3 != 0 else 0.4) for i in range(12)}\n"
            "    print(_render(main(gold, scores)))\n"
        ),
    },
}

# Lines to drop when inlining: future imports (re-emitted once at top), and any
# intra-repo imports (the whole point is that there is no package to import from).
_DROP = re.compile(r"^\s*from\s+__future__\s|^\s*from\s+\.|^\s*from\s+core(\.|\s|$)")


def _strip_module(path: str) -> str:
    src = open(os.path.join(ROOT, path)).read()
    kept = [ln for ln in src.splitlines() if not _DROP.match(ln)]
    return "\n".join(kept).strip()


def _strip_entry(path: str) -> str:
    """Keep the entrypoint's helpers and main, drop its header and __main__ block."""
    src = open(os.path.join(ROOT, path)).read()
    # Cut everything from the module docstring/imports up to the first helper or
    # `def main`, and drop the trailing `if __name__` block (we append our own).
    src = re.sub(r'^.*?(?=\ndef _|\ndef main)', "", src, count=1, flags=re.DOTALL)
    src = re.sub(r"\nif __name__ == .__main__.:.*$", "", src, flags=re.DOTALL)
    kept = [ln for ln in src.splitlines() if not _DROP.match(ln)]
    return "\n".join(kept).strip()


def build(name: str, spec: dict) -> str:
    parts = [
        '"""Standalone Windmill runnable (auto-generated by scripts/build_standalone.py).',
        "",
        "Paste this whole file into a Windmill Python script. Pure stdlib, no imports",
        "from this repo. Call main(...) from Windmill; the __main__ block is a local demo.",
        '"""',
        "from __future__ import annotations",
        "",
        "import math",
        "import random",
        "from dataclasses import dataclass, field",
        "",
    ]
    for core_path in spec["core"]:
        parts.append(f"# ---- inlined from {core_path} ----")
        parts.append(_strip_module(core_path))
        parts.append("")
    parts.append(f"# ---- entrypoint from {spec['entry']} ----")
    parts.append(_strip_entry(spec["entry"]))
    parts.append("")
    parts.append("")
    parts.append(spec["demo"])
    return "\n".join(parts)


def main() -> None:
    out_dir = os.path.join(ROOT, "windmill", "standalone")
    os.makedirs(out_dir, exist_ok=True)
    for name, spec in TARGETS.items():
        code = build(name, spec)
        out = os.path.join(out_dir, f"{name}_standalone.py")
        open(out, "w").write(code)
        print(f"wrote {out} ({len(code.splitlines())} lines)")


if __name__ == "__main__":
    main()
